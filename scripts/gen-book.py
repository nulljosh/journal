"""The journal as a short book: one chapter per post in _posts/, to book/index.html. `python3 scripts/gen-book.py`.
Reads only ## headings and paragraphs, which is all the posts use. Styles are plank's book.css on this repo's tokens."""
import glob, html, json, os, re, urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
MONTHS = "January February March April May June July August September October November December".split()


def meta(text, key):
    m = re.search(rf'^{key}: "?(.*?)"?$', text, re.M)
    return m.group(1) if m else ""


def body(text):
    text = re.sub(r"\{%.*?%\}", "", text.split("---", 2)[2])
    out = []
    for block in re.split(r"\n\s*\n", text.strip()):
        block = html.escape(block.strip(), quote=False)
        out.append(f"<h2>{block[3:]}</h2>" if block.startswith("## ") else f"<p>{block}</p>")
    return "\n".join(out)


CREDITS = json.load(open("book/img/credits.json"))  # n, alt, caption, Commons file name, license: public domain portraits from Wikimedia Commons
chapters, toc = [], []
for n, path in enumerate(sorted(glob.glob("_posts/*.md")), 1):
    text = open(path).read()
    y, m, d = meta(text, "date").split()[0].split("-")
    c = CREDITS[n - 1]
    page = "https://commons.wikimedia.org/wiki/File:" + urllib.parse.quote(c["file"].replace(" ", "_"))
    banner = (f'<figure class="banner"><img src="img/{n}.jpg" alt="{html.escape(c["alt"])}" height="380" loading="lazy">'
              f'<figcaption>{html.escape(c["caption"])} Public domain, <a href="{page}">via Wikimedia Commons</a>.</figcaption></figure>')
    cid, title = f"c{n}", html.escape(meta(text, "title"))
    toc.append(f'<li><a href="#{cid}"><small>{n}</small>{title}</a></li>')
    chapters.append(f'<section class="chapter" id="{cid}"><header class="opener"><p class="chap-no"><span>{MONTHS[int(m) - 1]} {y}</span><b>{n}</b></p></header>\n{banner}\n'
                    f'<h1>{title}</h1>\n<p class="lede">{html.escape(meta(text, "description"))}</p>\n{body(text)}</section>')

TOKENS = open("brand/tokens.css").read()  # inlined: Safari will not read ../ from a file:// page, and the book should open from anywhere
toc, chapters = "\n".join(toc), "\n".join(chapters)
open("book/index.html", "w").write(f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>The Journal, February to November</title>
<script>document.documentElement.dataset.theme = matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light"</script><style>{TOKENS}</style><link rel="stylesheet" href="book.css">
<style>.lede {{ font-style: italic; color: var(--text2); }} .banner {{ margin: 0 0 28px; padding: 24px 16px 16px; background: var(--bg2); border-radius: 4px; text-align: center; }} .banner img {{ display: block; margin: 0 auto; height: 380px; width: auto; max-width: 100%; object-fit: contain; border-radius: 2px; }} .banner figcaption {{ margin-top: 14px; font: 13px/1.4 var(--font); color: var(--text2); }} .quiz, .pdf, .edit {{ display: none; }}</style></head>
<body><!-- generated by scripts/gen-book.py from _posts/*.md; edit those, not this -->
<header class="bar"><span class="brand">Journal</span><span class="crumb">The Book</span></header>
<div class="layout"><nav class="toc" aria-label="Chapters"><p class="label">Chapters</p><ol>
{toc}
</ol></nav><main class="book"><div class="cover"><p class="label">The Journal</p>
<p class="cover-h">Ten months of building things alone.</p>
<p class="cover-sub">February to November 2026: an operating system from scratch, thirty apps on the App Store, a lot of rejections, and what it all taught me.</p>
<p class="cover-by">Joshua Trommel</p></div>
{chapters}
</main></div></body></html>
""")
print(f"wrote book/index.html, {len(toc.splitlines())} chapters")
